function renderIssueForm(code){
  if(!Object.prototype.hasOwnProperty.call(copies,code))throw new Error('Unknown Issue Form locale: '+code);
  const en=copies.en,loc=copies[code],label=key=>code==='en'?en[key]:en[key]+' / '+loc[key],y=JSON.stringify;
  const lines=[
    'name: '+y(label('name')),'description: '+y(label('description')),'title: "[Bug] "','body:',
    '  - type: textarea','    id: problem','    attributes:',
    '      label: '+y(label('what')),'      description: '+y(label('whatHelp')),'      placeholder: '+y(label('whatExample')),
    '    validations:','      required: true',
    '  - type: dropdown','    id: surface','    attributes:',
    '      label: '+y(label('interface')),'      description: '+y(label('interfaceHelp')),
    '      options:','        - Mobile','        - Desktop','        - Other or unsure',
    '    validations:','      required: true',
    '  - type: input','    id: other_environment','    attributes:',
    '      label: '+y(label('other')),'      description: '+y(label('otherHelp')),'      placeholder: '+y(label('otherExample')),
    '  - type: input','    id: weig_version','    attributes:',
    '      label: '+y(label('weig')),'      description: '+y(label('weigHelp')),
    '      placeholder: "1.2.2-A74(abcdef0)"','    validations:','      required: true',
    '  - type: input','    id: qb_version','    attributes:',
    '      label: '+y(label('qbit')),'      placeholder: "5.2.4"','    validations:','      required: true',
    '  - type: input','    id: browser_os','    attributes:',
    '      label: '+y(label('browser')),'      placeholder: '+y(label('browserExample')),
    '  - type: input','    id: webui_locale','    attributes:',
    '      label: '+y(label('locale')),'      description: '+y(label('localeHelp')),'      placeholder: '+y(code),
    '  - type: upload','    id: attachments','    attributes:',
    '      label: '+y(label('attach')),'      description: '+y(label('attachHelp')),
    '    validations:','      required: false','      accept: ".png,.jpg,.jpeg,.gif,.webp,.log,.txt,.json,.zip"'
  ];
  return lines.join('\n')+'\n';
}
function issueFormPaths(){return Object.keys(copies).map(code=>({code,path:'.github/ISSUE_TEMPLATE/bug_report'+(code==='en'?'':'_'+code)+'.yml'}));}

export {renderIssueForm,issueFormPaths};
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const check=process.argv.includes('--check');
  for(const item of issueFormPaths()){
    const full=path.join(root,item.path),expected=renderIssueForm(item.code);
    if(check){if(!fs.existsSync(full)||fs.readFileSync(full,'utf8')!==expected)throw new Error('Stale Issue Form: '+item.path);}
    else {fs.mkdirSync(path.dirname(full),{recursive:true});fs.writeFileSync(full,expected,'utf8');}
  }
  console.log('Localized Issue Forms '+(check?'verified':'generated')+': '+issueFormPaths().length);
}
