import assert from 'node:assert/strict';
import fs from 'node:fs';
const ps=fs.readFileSync(new URL('../installers/install.ps1',import.meta.url),'utf8');
const candidate=fs.readFileSync(new URL('./candidate-deployment.sh',import.meta.url),'utf8');
assert.match(ps,/Destination="\$env:LOCALAPPDATA\\weig-qb-webui"/);
assert.match(ps,/function Verify-PackageChecksum[\s\S]*ArchiveName/);
assert.match(ps,/manifest\.json[\s\S]*ConvertFrom-Json/);
assert.equal((ps.match(/Verify-PackageChecksum \$manifestFile \$sumFile 'manifest\.json'/g)||[]).length,2,'stable canonical and dev Windows manifest consumers must verify manifest.json before ConvertFrom-Json');
assert.match(ps,/rootFolder[^\n]*weig-qb-webui/);
assert.match(ps,/zipArchive[^\n]*weig-qb-webui\.zip/);
assert.match(ps,/archiveName='WeiG-qB-WebUI\.zip'/,'historical Release compatibility must remain bounded');
assert.match(ps,/DevDistBase\/manifest\.json/);
assert.match(candidate,/PACKAGE="\$CANDIDATE_DIR\/weig-qb-webui\.zip"/);
assert.match(candidate,/TAR_PACKAGE="\$CANDIDATE_DIR\/weig-qb-webui\.tar\.gz"/);
assert.match(candidate,/MANIFEST="\$CANDIDATE_DIR\/manifest\.json"/);
assert.match(candidate,/LINUX_INSTALLER="\$CANDIDATE_DIR\/install\.sh"/);
assert.match(candidate,/releases\/download\/v"\$WEIG_CANDIDATE_VERSION"\/manifest\.json/);
assert.match(candidate,/artifactSetSha256:true/);
assert.match(candidate,/DEST="\$CONFIG_ROOT\/weig-qb-webui"/);
assert.match(candidate,/QB_ROOT='\/config\/weig-qb-webui'/);
assert.match(candidate,/path\.join\(hostConfigRoot,'weig-qb-webui'\)/,'candidate install metadata must use the same canonical Docker path as the installer invocation');
assert.doesNotMatch(candidate,/weig_qb-webui|WeiG_qB-WebUI/,'candidate deployment must not retain legacy filesystem names as current expectations');
console.log('Windows/candidate artifact consumption contract passed.');
