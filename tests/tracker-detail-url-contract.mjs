import assert from 'node:assert/strict';
import fs from 'node:fs';
const app=fs.readFileSync(new URL('../webui/private/scripts/app.js',import.meta.url),'utf8');
const ui=fs.readFileSync(new URL('../webui/private/scripts/ui.js',import.meta.url),'utf8');
const start=app.indexOf('async function renderTrackers');
const end=app.indexOf('async function renderPeers',start);
assert.ok(start>=0&&end>start,'renderTrackers owner must exist');
const tracker=app.slice(start,end);
assert.ok(tracker.includes("trackerUrl=detailValue('trackers',t,'url','')"),'Tracker runtime must consume the exact source-proven API url field');
assert.ok(tracker.includes("url.textContent=trackerUrl||'Tracker'")&&tracker.includes("url.title=trackerUrl||''"),'fallback row rendering must retain the exact qB URL and tooltip');
assert.ok(!tracker.includes('U.normalizeTracker(trackerUrl)'),'Tracker detail display/edit must not normalize or redact URL');
assert.match(ui,/cell\.title=cell\.textContent;if\(isUrl\)\{cell\.style\.whiteSpace='nowrap';cell\.style\.overflow='hidden';cell\.style\.textOverflow='ellipsis';\}/,'shared Detail renderer must keep exact URL in tooltip and render it as a single-line ellipsis');
assert.doesNotMatch(ui,/overflowWrap='anywhere'|wordBreak='break-word'/,'Tracker URL presentation must not wrap');
console.log('Tracker detail URL contract passed: exact qB URL value is preserved, single-line ellipsized, and fully available by tooltip without normalization.');
