import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const transfer=read('webui/private/scripts/transfer.js');
const columns=read('webui/private/scripts/column-configurator.js');
const logs=read('webui/private/scripts/logs.js');
const rss=read('webui/private/scripts/rss.js');
assert.match(transfer,/subject=limitMode==='alt'/);
assert.match(transfer,/W\.Feedback&&W\.Feedback\.receipt/);
assert.match(transfer,/globalDownloadLimit[\s\S]*globalUploadLimit/);
assert.match(columns,/function receipt\(subject,label,value\)/);
assert.match(columns,/check\.onchange=function\(\).*receipt/s);
assert.match(columns,/delta<0\?'↑':'↓'/);
assert.match(logs,/function receipt\(label,value\)/);
assert.match(logs,/refresh\.addEventListener\('click',async function/);
assert.match(logs,/receipt\(tr\('logs\.ui\.follow'/);
assert.match(rss,/receipt\('RSS Downloader'/);
assert.ok(!rss.includes("receipt('RSS',tr('rss.workspace.feed')"),'RSS Feed completion must stay owned by its processing card, not emit a second receipt');
assert.ok(!/schedulePoll\(\)[\s\S]{0,200}receipt\(/.test(logs),'background log polling must not emit receipts');
const app=read('webui/private/scripts/app.js');
assert.match(app,/function operationReceipt\(subject,label,value,kind\)/);
assert.match(app,/var submitted=await executeDetailAction/);
assert.match(app,/notice\.update\('',\s*'success',\{receipt:\{subject:addSubject/);
assert.match(app,/receipt:\{subject:'RSS',results:\[\{label:tr\('rss\.addedTitle'/);
console.log('A25 B3 contract passed: shared semantic receipts cover transfer, columns, logs, Add, Detail and RSS user commits without duplicate polling/Feed noise.');
